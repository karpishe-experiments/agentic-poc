import { mkdir, rm } from "node:fs/promises";
import path from "node:path";
import { migrate } from "drizzle-orm/libsql/migrator";
import { createDatabase } from "@/db/client";

const runtimeRoot = path.resolve(process.cwd(), "output", "playwright", "runtime");
const approvedRoot = path.resolve(process.cwd(), "output", "playwright");
if (!runtimeRoot.startsWith(`${approvedRoot}${path.sep}`)) throw new Error("Refusing to reset an e2e path outside output/playwright.");
await rm(runtimeRoot, { recursive: true, force: true });
await mkdir(runtimeRoot, { recursive: true });
process.env.DATABASE_URL = `file:${path.join(runtimeRoot, "booklets.db")}`;
process.env.DATA_ROOT = path.join(runtimeRoot, "assets");
process.env.MODEL_RUNTIME = "fake";
process.env.IMAGE_PROVIDER_MODE = "fake";
process.env.OPENAI_API_KEY ??= "e2e-fake-key";
const database = createDatabase(process.env.DATABASE_URL);
await migrate(database, { migrationsFolder: path.join(process.cwd(), "db", "migrations") });
database.$client.close();
await import("../db/seed");
console.log("Prepared isolated fake-provider Playwright data.");
